const CANVAS_WIDTH = 1080;
const CANVAS_HEIGHT = 1620;

/**
 * A thin hairline rectangle rendered as an inline SVG data URI, used as a
 * border "frame" image element. ImageNode/use-image load any valid <img>
 * src, including data URIs, so this gives a true 1-2px stroked border
 * without extending CanvasElementData with a new shape kind.
 */
function hairlineBorderSrc(color: string, strokeWidth = 2, inset = 36): string {
  const w = CANVAS_WIDTH - inset * 2;
  const h = CANVAS_HEIGHT - inset * 2;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">` +
    `<rect x="${strokeWidth / 2}" y="${strokeWidth / 2}" width="${w - strokeWidth}" height="${h - strokeWidth}" ` +
    `fill="none" stroke="${color}" stroke-width="${strokeWidth}"/></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

function borderElement(color: string, zIndex = 0, inset = 36, strokeWidth = 2): CanvasElementData {
  return {
    id: `border-${color.replace('#', '')}`,
    type: 'image',
    mediaKind: 'image',
    x: inset,
    y: inset,
    width: CANVAS_WIDTH - inset * 2,
    height: CANVAS_HEIGHT - inset * 2,
    rotation: 0,
    zIndex,
    locked: true,
    src: hairlineBorderSrc(color, strokeWidth, inset),
  };
}

